create table if not exists public.contributions (
  id bigint generated by default as identity primary key,
  amount_cents integer not null,
  tier text not null,
  display_name text not null,
  x_handle text,
  message text not null default '',
  product_name text,
  product_url text,
  product_pitch text,
  stripe_session_id text,
  click_count integer not null default 0,
  approved boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists contributions_stripe_session_idx
  on public.contributions (stripe_session_id)
  where stripe_session_id is not null;

create index if not exists contributions_rank_idx
  on public.contributions (amount_cents desc, created_at asc);

create table if not exists public.pending_payments (
  id text primary key,
  payload text not null,
  created_at timestamptz not null default now()
);

alter table public.contributions enable row level security;
alter table public.pending_payments enable row level security;

drop policy if exists contributions_public_read on public.contributions;
create policy contributions_public_read
  on public.contributions for select
  using (true);

drop policy if exists contributions_public_insert on public.contributions;
create policy contributions_public_insert
  on public.contributions for insert
  with check (true);

drop policy if exists contributions_public_update on public.contributions;
create policy contributions_public_update
  on public.contributions for update
  using (true)
  with check (true);

drop policy if exists pending_public_all on public.pending_payments;
create policy pending_public_all
  on public.pending_payments for all
  using (true)
  with check (true);

